"""Write the experiment's main run as JSON (docs/experiment-results.json), for the figures.

    python scripts/export_experiment_json.py            # (re)write it
    python scripts/export_experiment_json.py --check    # exit 1 if the committed file differs
    python scripts/export_experiment_json.py --run openai_gpt-6-luna-7f88fda14e

It reads the private data (experiment/data/, or COMPLIANCELENS_EXPERIMENT_DATA) and
labels.csv with the same functions as `python -m experiment.lab analyze`, and writes
nothing there. The JSON holds numbers, verdicts and case IDs only: no folder or picture
paths and none of the AI's text, so it can be committed and the figures rebuilt from it
(scripts/plot_experiment.py). With no --run, the one main (not pilot) run is used.

Exit codes: 0 done, 1 the committed file differs, 2 the data can't be read.
"""

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))  # run as a script: the experiment package is not installed

from experiment.lab import analyze, capture, cases, labels, labels_path, run  # noqa: E402

OUTPUT = ROOT / "docs" / "experiment-results.json"
NOTE = (
    "Generated by scripts/export_experiment_json.py from the private experiment data;"
    " don't edit. The same numbers as docs/experiment-results.md."
)


class ExportError(RuntimeError):
    """The data can't be exported as it is; the message says why."""


def main_run(name: str | None = None) -> Path:
    """The run folder to export: `name`, or the only main run there is."""
    if name:
        folder = run.runs_dir() / name
        if not (folder / "config.json").is_file():
            raise ExportError(f"no run called {name}")
        return folder
    found = []
    for folder in sorted(run.runs_dir().glob("*")):
        config = folder / "config.json"
        if config.is_file() and not json.loads(config.read_text(encoding="utf-8"))["pilot"]:
            found.append(folder)
    if len(found) != 1:
        names = ", ".join(folder.name for folder in found) or "none"
        raise ExportError(f"choose the main run with --run (main runs: {names})")
    return found[0]


def export(name: str | None = None) -> dict:
    """The main run's analysis as JSON-ready data, with the labellers' agreement."""
    folder = main_run(name)
    try:
        records = capture.load_captured()
        rows = labels.read_labels(labels_path())
        main_cases = {case.id for case in cases.select(cases.load_cases())}
        result = analyze.analyze(folder, records, rows, main_cases)
        final = labels.final_labels(rows, [r for r in records if r["case"]["id"] in main_cases])
    except (
        analyze.AnalysisError,
        capture.CaptureError,
        cases.CasesError,
        labels.LabelsError,
        OSError,
    ) as e:
        raise ExportError(str(e))
    if result["pilot"]:
        raise ExportError(f"{folder.name} is a pilot run: export the main run")
    return {
        "note": NOTE,
        **analyze.as_json(result),
        "final_labels": dict(sorted(Counter(final.values()).items())),
        "agreement": labels.agreement(rows),
    }


def text(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    name = argv[argv.index("--run") + 1] if "--run" in argv[:-1] else None
    try:
        output = text(export(name))
    except ExportError as e:
        print(f"Can't export the experiment's results: {e}")
        return 2
    shown = OUTPUT.relative_to(ROOT).as_posix()
    if check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != output:
            print(f"{shown} differs from the data: run scripts/export_experiment_json.py")
            return 1
        print(f"{shown} matches the data")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(output, encoding="utf-8")
    print(f"wrote {shown}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
