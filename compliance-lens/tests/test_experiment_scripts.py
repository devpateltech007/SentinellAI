def test_the_committed_json_has_the_numbers_of_the_results_page():
    """docs/experiment-results.json and .md come from the same analysis (CI has no data)."""
    result = json.loads((ROOT / "docs" / "experiment-results.json").read_text(encoding="utf-8"))
    page = (ROOT / "docs" / "experiment-results.md").read_text(encoding="utf-8")

    def rate(value):
        return analyze.Rate(value["k"], value["n"]).text()

    assert f"## {result['model']} — {result['run']}" in page
    for first, second in (("overall", "vs_state"), ("case_level", "case_level_vs_state")):
        for key, label in analyze.MEASURES:
            row = f"| {label} | {rate(result[first][key])} | {rate(result[second][key])} |"
            assert row in page
    for rule, rates in result["by_rule"].items():
        row = " | ".join([rule, *(rate(rates[key]) for key in analyze.SHORT)])
        assert f"| {row} |" in page
    assert result["final_labels"] == {"FAIL": 30, "PASS": 21, "REVIEW": 4}
    assert f"Cohen's κ = {result['agreement']['kappa']:.2f}" in page
    assert '"/' not in json.dumps(result)  # no paths


