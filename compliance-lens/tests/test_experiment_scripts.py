def test_the_export_has_the_numbers_and_no_paths(data, output, tmp_path, capsys):
    root, records = data
    write_run(root, records)
    write_run(root, records[:1], name="openai_m-pilot-1", pilot=True)  # never exported
    assert export.main([]) == 0
    assert "wrote docs/experiment-results.json" in capsys.readouterr().out
    text = output.read_text(encoding="utf-8")
    assert str(tmp_path) not in text and ".png" not in text and '"folder"' not in text
    result = json.loads(text)
    assert result["note"].startswith("Generated by scripts/export_experiment_json.py")
    assert (result["run"], result["answers"], result["pilot"]) == ("openai_m-abc", 9, False)
    assert result["overall"]["accuracy"] == analyze.Rate(6, 9).as_dict() | {
        "ci95": list(analyze.wilson(6, 9))
    }
    # One per case: PASS, FAIL and REVIEW, each the label: 3 of 3.
    assert (result["case_level"]["accuracy"]["k"], result["case_level"]["accuracy"]["n"]) == (3, 3)
    assert result["final_labels"] == {"FAIL": 1, "PASS": 1, "REVIEW": 1}
    assert result["agreement"]["kappa"] == 1.0 and result["agreement"]["agreed"] == 3
    assert not result["status"]["complete"]  # the other main cases of cases.yaml are missing
    assert export.main(["--check"]) == 0
    assert "matches the data" in capsys.readouterr().out
    output.write_text(text.replace("openai/m", "openai/other"), encoding="utf-8")
    assert export.main(["--check"]) == 1
    assert "differs from the data" in capsys.readouterr().out
    output.unlink()
    assert export.main(["--check"]) == 1


def test_the_export_picks_the_main_run(data, output, capsys):
    root, records = data
    assert export.main([]) == 2
    assert "main runs: none" in capsys.readouterr().out
    write_run(root, records, name="run-a")
    write_run(root, records, name="run-b")
    write_run(root, records, name="pilot-c", pilot=True)
    assert export.main([]) == 2
    assert "choose the main run with --run (main runs: run-a, run-b)" in capsys.readouterr().out
    assert export.main(["--run", "nope"]) == 2
    assert "no run called nope" in capsys.readouterr().out
    assert export.main(["--run", "pilot-c"]) == 2
    assert "pilot-c is a pilot run" in capsys.readouterr().out
    assert export.main(["--run", "run-b"]) == 0
    assert json.loads(output.read_text(encoding="utf-8"))["run"] == "run-b"


