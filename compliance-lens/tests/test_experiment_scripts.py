def test_the_examples_are_cut_and_the_names_covered(pictures, tmp_path, capsys):
    assert crops.main([]) == 0
    out = capsys.readouterr().out
    assert "wrote docs/figures/example-aws02-no-console.png (1111 × 160)" in out
    assert "Look at every picture before you commit it" in out
    for example in crops.EXAMPLES:
        with Image.open(tmp_path / "docs" / "figures" / f"example-{example.case_id}.png") as image:
            left, top, right, bottom = example.box
            assert image.size == (right - left, bottom - top)
            for (_, _, c_right, c_bottom), _ in example.covers:
                corner = (c_right - left - 1, c_bottom - top - 1)  # no text there
                assert image.getpixel(corner) == (0xE9, 0xEB, 0xED)


def test_a_missing_or_changed_picture_is_refused(pictures, tmp_path, capsys):
    picture_path = pictures / "gh06-menu-open" / "page.png"
    Image.new("RGB", (1440, 900), "black").save(picture_path)
