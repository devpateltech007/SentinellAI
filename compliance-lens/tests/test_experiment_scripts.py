def answer(case_id, rule, repeat, verdict):
    return {
        "case_id": case_id,
        "repeat": repeat,
        "rule": rule,
        "verdict": verdict,
        "status": "unsure" if verdict == "NEEDS REVIEW" else "accepted",
        "confidence": "high",
        "observed": "",
        "attempts": 1,
        "invalid_attempts": 0,
        "calls": 1,
        "input_tokens": 1000,
        "output_tokens": 100,
        "cost_usd": 0.0002,
        "elapsed_ms": 3000,
    }


@pytest.fixture
def data(temp_storage):
    """Three captured cases with their labels, where conftest points the experiment."""
    root = temp_storage / "experiment"
    records = captured(root, SPECS)
    rows, _ = labels.update_rows(records, {})
    for case_id, label in FINAL.items():
        rows[case_id].update(evidence_label_a=label, evidence_label_b=label, evidence_label=label)
    labels.write_labels(root / "labels.csv", rows)
    return root, records


def write_run(root, records, name="openai_m-abc", pilot=False):
    folder = root / "runs" / name
    folder.mkdir(parents=True)
    config = {
        "model": "openai/m",
        "pilot": pilot,
        "repeats": 3,
        "cases": {r["case"]["id"]: r["pixel_sha256"] for r in records},
    }
    (folder / "config.json").write_text(json.dumps(config))
    answers = [
        answer(r["case"]["id"], r["case"]["rule"], repeat, verdict)
        for r in records
        for repeat, verdict in enumerate(VERDICTS[r["case"]["id"]], start=1)
    ]
    (folder / "predictions.jsonl").write_text("".join(json.dumps(a) + "\n" for a in answers))
    return folder


