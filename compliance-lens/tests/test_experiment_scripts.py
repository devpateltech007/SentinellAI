def test_every_example_box_fits_the_picture():
    for example in crops.EXAMPLES:
        left, top, right, bottom = example.box
        assert 0 <= left < right <= 1440 and 0 <= top < bottom <= 900
        for (c_left, c_top, c_right, c_bottom), _ in example.covers:
            assert left <= c_left < c_right <= right and top <= c_top < c_bottom <= bottom


